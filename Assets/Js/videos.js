const videosPerPage = 6;
const videoGrid = document.getElementById("videoGrid");
const pagination = document.getElementById("pagination");

let currentPage = parseInt(localStorage.getItem("videoCurrentPage")) || 1;

function renderVideos() {
  const totalPages = Math.ceil(videos.length / videosPerPage);

  if (currentPage > totalPages) {
    currentPage = totalPages || 1;
  }

  const start = (currentPage - 1) * videosPerPage;
  const end = start + videosPerPage;
  const pageVideos = videos.slice(start, end);

  videoGrid.innerHTML = pageVideos.map(video => `
    <a href="${video.page}" class="video-card" aria-label="${video.title}">
      <div class="video-preview-wrapper">
        <div class="play-icon" aria-hidden="true">▶</div>
        <div class="video-duration" aria-label="Video duration ${video.duration}">
          ${video.duration}
        </div>

        <img
          src="${video.thumb}"
          alt="${video.title}"
          class="video-thumb"
          loading="lazy"
        >

        <video
          class="preview-video"
          muted
          loop
          playsinline
          preload="none"
          aria-hidden="true"
        >
          <source src="${video.preview}" type="video/mp4">
        </video>
      </div>

      <h3>${video.title}</h3>
    </a>
  `).join("");
}

function createPageButton(pageNum, isActive = false) {
  return `
    <button
      class="page-btn ${isActive ? "active" : ""}"
      data-page="${pageNum}"
      aria-label="Go to page ${pageNum}"
      ${isActive ? 'aria-current="page"' : ""}
    >
      ${pageNum}
    </button>
  `;
}

function renderPagination() {
  const totalPages = Math.ceil(videos.length / videosPerPage);

  if (totalPages <= 1) {
    pagination.innerHTML = "";
    return;
  }

  let buttons = "";

  if (totalPages <= 4) {
    for (let i = 1; i <= totalPages; i++) {
      buttons += createPageButton(i, i === currentPage);
    }
  } else {
  if (currentPage > 1) {
    buttons += `
      <button
        class="page-btn next-btn"
        data-page="${currentPage - 1}"
        aria-label="Go to previous page"
      >
        Prev
      </button>
    `;
  }

  buttons += createPageButton(1, currentPage === 1);

  if (currentPage > 3) {
    buttons += `<span class="pagination-dots" aria-hidden="true">...</span>`;
  }

  if (currentPage <= 3) {
    for (let i = 2; i <= 3 && i < totalPages; i++) {
      buttons += createPageButton(i, i === currentPage);
    }
  }

  if (currentPage > 3 && currentPage < totalPages) {
    buttons += createPageButton(currentPage, true);
  }

  if (currentPage < totalPages - 2) {
    buttons += `<span class="pagination-dots" aria-hidden="true">...</span>`;
  }

  if (totalPages > 1) {
    buttons += createPageButton(totalPages, currentPage === totalPages);
  }

  if (currentPage < totalPages) {
    buttons += `
      <button
        class="page-btn next-btn"
        data-page="${currentPage + 1}"
        aria-label="Go to next page"
      >
        Next
      </button>
    `;
  }
}

  pagination.innerHTML = buttons;

  document.querySelectorAll(".page-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      currentPage = Number(btn.dataset.page);

      localStorage.setItem("videoCurrentPage", currentPage);

      renderVideos();
      renderPagination();

      videoGrid.scrollIntoView({
        behavior: "smooth",
        block: "start"
      });
    });
  });
}

renderVideos();
renderPagination();